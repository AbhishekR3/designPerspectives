/**
 * Canonical printer: Model → LikeC4 source files (plan Q6). Deterministic: sorted, 2-space indent, LF,
 * one trailing newline. Output files: model/spec.c4, model/model.c4, model/deployment.c4, model/views.c4.
 */
import {
  ASYNC_RELATIONSHIP_KINDS,
  RELATIONSHIP_KINDS,
  sortModel,
  type DeploymentInstance,
  type DeploymentNode,
  type Element,
  type Model,
  type Relationship,
  type SourceFile,
  type ViewDef,
} from "@designperspectives/contracts";
import {
  DEPLOYMENT_KIND_TO_LIKEC4,
  ELEMENT_KIND_TO_LIKEC4,
  ELEMENT_SHAPES,
  GROUP_TYPE_METADATA,
  REL_KEY_METADATA,
  VIEW_ENV_TAG_PREFIX,
  VIEW_SCOPE_TAG_PREFIX,
  VIEW_TYPE_TAG_PREFIX,
  VIEW_TYPES_WITH_OF,
  idToTag,
  str,
} from "./dsl.js";
import { includeToDsl } from "./view-rules.js";

const HEADER = "// Generated by designPerspectives. Edit through the app or `dp`; hand edits are re-formatted on save.";

class Out {
  private readonly lines: string[] = [];
  private depth = 0;
  line(s: string): void {
    this.lines.push("  ".repeat(this.depth) + s);
  }
  /** Empty blocks collapse to `head` (element declarations) or `head {}` when `keepBraces` (top-level sections). */
  block(head: string, body: () => void, keepBraces = false): void {
    const at = this.lines.length;
    this.line(`${head} {`);
    this.depth++;
    body();
    this.depth--;
    if (this.lines.length > at + 1) this.line("}");
    else this.lines[at] = keepBraces ? `${this.lines[at]}}` : this.lines[at]!.slice(0, -2);
  }
  toString(): string {
    return [HEADER, ...this.lines].join("\n") + "\n";
  }
}

const last = (id: string): string => id.slice(id.lastIndexOf(".") + 1);

function childrenIndex<T extends { id: string }>(items: readonly T[]): Map<string | undefined, T[]> {
  const ids = new Set(items.map((i) => i.id));
  const index = new Map<string | undefined, T[]>();
  for (const item of items) {
    const p = item.id.includes(".") ? item.id.slice(0, item.id.lastIndexOf(".")) : undefined;
    const key = p !== undefined && ids.has(p) ? p : p === undefined ? undefined : `missing:${p}`;
    index.set(key, [...(index.get(key) ?? []), item]);
  }
  return index;
}

function printSpec(model: Model): string {
  const o = new Out();
  const tags = new Set<string>();
  for (const e of model.elements) e.tags?.forEach((t) => tags.add(t));
  for (const r of model.relationships) r.tags?.forEach((t) => tags.add(t));
  for (const n of model.deploymentNodes) n.tags?.forEach((t) => tags.add(t));
  for (const v of model.views) viewTags(v).forEach((t) => tags.add(t));
  o.block("specification", () => {
    for (const kind of Object.values(ELEMENT_KIND_TO_LIKEC4).sort()) {
      const shape = ELEMENT_SHAPES[kind];
      o.block(`element ${kind}`, () => {
        if (shape) o.block("style", () => o.line(`shape ${shape}`));
      });
    }
    for (const kind of Object.values(DEPLOYMENT_KIND_TO_LIKEC4).sort()) o.line(`deploymentNode ${kind}`);
    for (const kind of [...RELATIONSHIP_KINDS].sort()) {
      o.block(`relationship ${kind}`, () => {
        if (ASYNC_RELATIONSHIP_KINDS.includes(kind)) o.line("line dashed");
      });
    }
    for (const t of [...tags].sort()) o.line(`tag ${t}`);
  });
  return o.toString();
}

function props(o: Out, x: { tags?: string[] | undefined; technology?: string | undefined; description?: string | undefined }): void {
  for (const t of [...(x.tags ?? [])].sort()) o.line(`#${t}`);
  if (x.technology?.trim()) o.line(`technology ${str(x.technology)}`);
  if (x.description?.trim()) o.line(`description ${str(x.description)}`);
}

function printElements(o: Out, index: Map<string | undefined, Element[]>, parent: string | undefined): void {
  for (const e of index.get(parent) ?? []) {
    o.block(`${last(e.id)} = ${ELEMENT_KIND_TO_LIKEC4[e.kind]} ${str(e.title)}`, () => {
      props(o, e);
      if (e.groupType) o.block("metadata", () => o.line(`${GROUP_TYPE_METADATA} ${str(e.groupType!)}`));
      printElements(o, index, e.id);
    });
  }
}

function printRelationship(o: Out, r: Relationship): void {
  o.block(`${r.source} -[${r.kind}]-> ${r.target} ${str(r.label)}`, () => {
    props(o, { tags: r.tags, technology: r.technology });
    if (r.key) o.block("metadata", () => o.line(`${REL_KEY_METADATA} ${str(r.key!)}`));
  });
}

function printModelFile(model: Model): string {
  const o = new Out();
  o.block("model", () => {
    const index = childrenIndex(model.elements);
    const orphans = [...index.keys()].filter((k) => k?.startsWith("missing:"));
    if (orphans.length) throw new Error(`printer: missing parent element(s) ${orphans.map((k) => k!.slice(8)).join(", ")}`);
    printElements(o, index, undefined);
    for (const r of model.relationships) printRelationship(o, r);
  }, true);
  return o.toString();
}

type DeploymentItem = DeploymentNode | (DeploymentInstance & { kind: "instance" });

function printDeploymentItems(o: Out, index: Map<string | undefined, DeploymentItem[]>, parent: string | undefined): void {
  for (const item of index.get(parent) ?? []) {
    if (item.kind === "instance") {
      o.line(`${last(item.id)} = instanceOf ${item.of}`);
      continue;
    }
    o.block(`${last(item.id)} = ${DEPLOYMENT_KIND_TO_LIKEC4[item.kind]} ${str(item.title)}`, () => {
      props(o, item);
      printDeploymentItems(o, index, item.id);
    });
  }
}

function printDeploymentFile(model: Model): string {
  const o = new Out();
  const items: DeploymentItem[] = [
    ...model.deploymentNodes,
    ...model.deploymentInstances.map((i) => ({ ...i, kind: "instance" as const })),
  ].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  o.block("deployment", () => printDeploymentItems(o, childrenIndex(items), undefined), true);
  return o.toString();
}

export function viewTags(v: ViewDef): string[] {
  const tags = [`${VIEW_TYPE_TAG_PREFIX}${v.type}`];
  if (v.type === "dynamic" && v.scope) tags.push(`${VIEW_SCOPE_TAG_PREFIX}${idToTag(v.scope)}`);
  if (v.type === "deployment" && v.environment) tags.push(`${VIEW_ENV_TAG_PREFIX}${idToTag(v.environment)}`);
  return tags;
}

function viewHead(v: ViewDef): string {
  if (v.type === "dynamic") return `dynamic view ${v.id}`;
  if (v.type === "deployment") return `deployment view ${v.id}`;
  const of = VIEW_TYPES_WITH_OF.includes(v.type) && v.scope ? ` of ${v.scope}` : "";
  return `view ${v.id}${of}`;
}

function printView(o: Out, v: ViewDef, model: Model): void {
  o.block(viewHead(v), () => {
    for (const t of viewTags(v)) o.line(`#${t}`);
    o.line(`title ${str(v.title)}`);
    if (v.description?.trim()) o.line(`description ${str(v.description)}`);
    for (const s of v.steps ?? []) o.line(`${s.source} -> ${s.target} ${str(s.label)}`);
    const include = includeToDsl(v, model);
    if (include.length) o.line(`include ${include.join(", ")}`);
    if (v.exclude?.length) o.line(`exclude ${v.exclude.join(", ")}`);
  });
}

function printViewsFile(model: Model): string {
  const o = new Out();
  o.block("views", () => model.views.forEach((v) => printView(o, v, model)), true);
  return o.toString();
}

export function printModel(input: Model): SourceFile[] {
  const model = sortModel(input);
  return [
    { path: "model/deployment.c4", content: printDeploymentFile(model) },
    { path: "model/model.c4", content: printModelFile(model) },
    { path: "model/spec.c4", content: printSpec(model) },
    { path: "model/views.c4", content: printViewsFile(model) },
  ];
}
